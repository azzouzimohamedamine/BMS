"""Generate docs/EXPERIMENTAL_RESULTS.md from results/metrics (no hand-typed numbers in the tables)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import pandas as pd  # noqa: E402

from bms.utils.config import repo_root  # noqa: E402

R = repo_root(); M = R / "results" / "metrics"

def md(df, nd=2):
    df = df.reset_index(); cols = list(df.columns)
    f = lambda v: f"{v:.{nd}f}" if isinstance(v, float) else str(v)
    return "| " + " | ".join(map(str, cols)) + " |\n|" + "---|" * len(cols) + "\n" + "\n".join("| " + " | ".join(f(v) for v in r) + " |" for r in df.to_numpy())

r = pd.read_csv(M / "soc_results.csv"); c = r[r.noise == "clean"]
cap = pd.read_csv(M / "soh_capacity_table.csv")
ph = c[c.protocol == "physics_T25C_lowI"].set_index(["test", "model"])[["MAE", "RMSE", "R2", "MaxAE"]]
em = c[c.protocol == "ekf_matched_own_params"].set_index("test")[["MAE", "RMSE", "R2", "MaxAE"]]
dd = c[c.protocol == "data_driven"].assign(case=lambda d: d.train + " → " + d.test)
order = ["random_forest", "hist_gradient_boosting", "gru", "gru_sf", "lstm", "lstm_sf"]
mae = dd.pivot_table(index="case", columns="model", values="MAE")[order]
r2 = dd.pivot_table(index="case", columns="model", values="R2")[order]
n = r[((r.protocol == "data_driven") & (r.train == "T25C_lowI") | (r.protocol == "physics_T25C_lowI")) & r.test.isin(["T00C_lowI", "T45C_lowI"])]
noise = n.groupby(["model", "noise"]).MAE.mean().unstack()[["clean", "low", "medium", "high", "i_bias_20mA"]]
tim = c.groupby("model").infer_ms_per_1k.mean().to_frame("ms / 1000 samples")
fs = pd.read_csv(M / "fault_simulated_benchmark.csv"); fr = pd.read_csv(M / "fault_real_data_summary.csv").set_index("dataset")
f1 = fs[fs.magnitude == 1.0].pivot_table(index="fault_type", columns="detector", values="event_detection_rate")[["iso", "ocsvm", "threshold", "flatline", "any"]]
f05 = fs[fs.magnitude == 0.5].pivot_table(index="fault_type", columns="detector", values="event_detection_rate")[["iso", "ocsvm", "threshold", "flatline", "any"]]

doc = f"""# Experimental results (auto-generated by `scripts/generate_results_doc.py`)

Errors are in **SOC percentage points** versus the *calculated* reference (see `METHODOLOGY.md`); first 10 min excluded; clean signals unless stated.
Figures: `results/figures/`.

## 1. Measured capacity / resistance per condition (NOT SOH)
{md(cap.set_index("dataset_id"), 4)}

## 2. Physics-based SOC (capacity + ECM calibrated on 25 °C; tested on unseen conditions)
{md(ph)}

`*_init70` = SOC₀ wrongly set to 70 %. The EKF corrects the initial error within the 10 min warm-up that is excluded from the metrics (see `fig03`).

EKF with parameters/capacity identified on the *same* test (optimistic upper bound, in-sample):
{md(em)}

## 3. Data-driven SOC — MAE by protocol (train → test)
{md(mae)}

R²:
{md(r2, 3)}

## 4. Noise robustness (SIMULATED perturbations; mean MAE over 0 °C and 45 °C tests, models fitted on 25 °C)
{md(noise)}

## 5. Inference time (ms per 1000 samples, 1 CPU core)
{md(tim)}

## 6. Fault diagnosis
Real data — windows flagged (statistical anomalies, detectors fitted on 0 °C + 45 °C):
{md(fr[['n_windows','flagged_iso','flagged_ocsvm','flagged_threshold','flagged_flatline','flagged_any']], 0)}

SIMULATED faults injected in the 25 °C signal — event detection rate, magnitude ×1.0:
{md(f1)}

magnitude ×0.5:
{md(f05)}

## 7. SOH / RUL
Not computed: one cycle per file and unverified nominal capacity (`results/experiment_logs/soh_rul_feasibility.json`).

## 8. Reading guide (what can and cannot be concluded)
* EKF vs CC: with a prior capacity that differs from the actual one, CC drifts linearly (3–6 points MAE here) and never recovers from a wrong SOC₀ (≈ 24–27 points); the EKF stays below ≈ 1 point MAE on all three unseen conditions, including the 1 A test.
* Trees reach the lowest errors on the 0.1 A cross-temperature cases, but this partly reflects (i) V ≈ OCV at 0.1 A and (ii) the per-test normalisation of the reference (see `LIMITATIONS.md` §5). They fail on the 1 A test (≈ 13–14 points).
* LSTM/GRU (16 units, NumPy) are worse than trees and the EKF here and very sensitive to input scaling under noise; this is not evidence against recurrent models in general.
* Nothing here validates behaviour under dynamic (drive-cycle) loads or over battery lifetime.
"""
(R / "docs" / "EXPERIMENTAL_RESULTS.md").write_text(doc, encoding="utf-8")
print("ok", len(doc))
